import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import guard from './guard.cjs';
import integrity from './integrity.cjs';
import {loadSession,resolveSessionFile} from '../hostlib/session-report.ts';
const root=path.dirname(fileURLToPath(import.meta.url));
const [manifest,surface,action]=process.argv.slice(2);
assert.ok(manifest,'Usage: control.mjs <cases.json> <surface> designer|arm [--confirmed-server] [--authorize-one-image] [--session UUID]');
const cfg=JSON.parse(fs.readFileSync(path.resolve(manifest),'utf8')).cases.find(item=>item.surface===surface);
assert.ok(cfg,'Choose desktop or vscode.');
const sha=value=>crypto.createHash('sha256').update(value).digest('hex');
const current=()=>JSON.parse(fs.readFileSync(path.join(cfg.workspace,'.probe/latest.json'),'utf8'));
const recorded=()=>{
  const explicit=process.argv.indexOf('--session');
  if(explicit<0) return loadSession(current().transcriptPath);
  const id=process.argv[explicit+1];
  assert.match(id??'',/^[a-f0-9]{8}(?:-[a-f0-9]{4}){3}-[a-f0-9]{12}$/i);
  return loadSession(resolveSessionFile(id));
};
const intact=()=>assert.ok(integrity.protectedState(cfg),'Protected native files, hooks or settings changed.');
intact();
if(action==='designer') {
  assert.ok(!fs.existsSync(path.join(cfg.workspace,'.probe/image-attempt.json')),'This image attempt is used; preserve the case.');
  const setup=recorded();
  assert.ok(guard.sameFolder(setup.cwd,cfg.workspace),'Actual setup folder differs.');
  assert.equal(setup.agentSetting,'orchestrator-digital-agency','Setup record must show native Chris.');
  const file=path.join(cfg.workspace,'.claude/settings.json'),settings=JSON.parse(fs.readFileSync(file,'utf8'));
  assert.equal(sha(JSON.stringify(settings.hooks)),cfg.settingsHooksSHA,'Test hooks changed.');
  settings.agent='agency-creative-designer';
  fs.writeFileSync(file,JSON.stringify(settings,null,2)+'\n');
  console.log('Close the Chris session, then start a NEW local GUI conversation in '+cfg.workspace+'; select Sonnet/low and paste stage-2-tool-check.txt.');
} else if(action==='arm') {
  assert.ok(process.argv.includes('--confirmed-server'),'Confirm in the UI that this project image-gen definition is selected with this assets/generated output directory; then add --confirmed-server. Do not arm an unresolved same-name Chat server.');
  assert.ok(!fs.existsSync(path.join(cfg.workspace,'.probe/image-attempt.json')),'The one attempt is already used.');
  assert.ok(process.argv.includes('--authorize-one-image'),'Separate explicit human image authorization is required.');
  const session=recorded();
  assert.ok(guard.sameFolder(session.cwd,cfg.workspace),'Actual GUI working folder differs.');
  assert.equal(session.agentSetting,'agency-creative-designer','Host record does not show the native designer active; preserve/report the record instead of generating.');
  const lead=session.agents.find(agent=>agent.isLead);
  assert.ok(lead.models.length && lead.models.every(model=>/sonnet/i.test(model)),'Choose Sonnet before any further prompt.');
  const events=fs.readdirSync(path.join(cfg.workspace,'.probe/events')).map(file=>JSON.parse(fs.readFileSync(path.join(cfg.workspace,'.probe/events',file),'utf8'))).filter(event=>!event.verification&&event.sessionId===session.sessionId);
  assert.ok(events.some(event=>event.kind==='PreToolUse'&&event.allowed),'Live test hooks have not been observed; do not generate.');
  assert.ok(lead.calls.some(call=>call.name==='ToolSearch'&&!call.isError&&call.result?.includes('[tool_reference mcp__image-gen__generate_image]')),'No successful host-record image tool reference; do not generate.');
  assert.ok(events.some(event=>event.kind==='PostToolUse'&&event.tool==='ToolSearch'&&event.imageToolListed),'No successful image tool lookup captured; do not generate.');
  fs.writeFileSync(path.join(cfg.workspace,'.probe/armed.json'),JSON.stringify({sessionId:session.sessionId,verifiedMainAgent:session.agentSetting,at:new Date().toISOString(),humanConfirmedSelectedServer:true}),{flag:'wx'});
  console.log('One attempt is armed for '+session.sessionId+'. Paste stage-3-one-image.txt in THAT SAME designer conversation.');
} else throw Error('Use designer or arm. This helper never starts Claude or reads provider configuration.');
